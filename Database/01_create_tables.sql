-- ============================================================================
-- SCRIPT: 01_create_tables.sql
-- PURPOSE: Create 7 core application tables in dependency order
-- SCHEMA: FINAL_APP | PDB: FINALPDB | TARGET: Oracle Database 19c
-- ============================================================================

-- Safely clean existing application tables if re-running
BEGIN
    FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN ('REGISTRATIONS', 'COURSEOFFERINGS', 'COURSES', 'TRAINEES', 'TRAINERS', 'CATEGORIES', 'ADMINS')) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/

-- ----------------------------------------------------------------------------
-- 1. Table: ADMINS
-- Purpose: System administrators managing system configuration and data
-- ----------------------------------------------------------------------------
CREATE TABLE ADMINS (
    AdminID         NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,
    Username        VARCHAR2(50) NOT NULL,
    PasswordHash    VARCHAR2(255) NOT NULL,
    PasswordSalt    VARCHAR2(64),
    Email           VARCHAR2(100) NOT NULL,
    FullName        VARCHAR2(100) NOT NULL,
    IsActive        NUMBER(1,0) DEFAULT 1 NOT NULL,
    CreatedAt       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UpdatedAt       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    LastLogin       TIMESTAMP
);

COMMENT ON TABLE ADMINS IS 'Administrator accounts for system governance and course catalog management';
COMMENT ON COLUMN ADMINS.AdminID IS 'Surrogate primary key generated by Oracle identity';
COMMENT ON COLUMN ADMINS.Username IS 'Unique login identifier for administrator';
COMMENT ON COLUMN ADMINS.PasswordHash IS 'Cryptographic password hash (BCrypt / PBKDF2)';
COMMENT ON COLUMN ADMINS.PasswordSalt IS 'Salt string utilized during hash derivation';

-- ----------------------------------------------------------------------------
-- 2. Table: CATEGORIES
-- Purpose: Training subject domains (e.g. Cloud Computing, Software Engineering)
-- ----------------------------------------------------------------------------
CREATE TABLE CATEGORIES (
    CategoryID      NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,
    CategoryName    VARCHAR2(100) NOT NULL,
    Description     VARCHAR2(500),
    CreatedAt       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UpdatedAt       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

COMMENT ON TABLE CATEGORIES IS 'Course thematic categories and professional domains';
COMMENT ON COLUMN CATEGORIES.CategoryID IS 'Surrogate primary key for category';
COMMENT ON COLUMN CATEGORIES.CategoryName IS 'Unique professional title of training domain';

-- ----------------------------------------------------------------------------
-- 3. Table: TRAINERS
-- Purpose: Instructors and course authors with credentials and biographies
-- ----------------------------------------------------------------------------
CREATE TABLE TRAINERS (
    TrainerID       NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,
    FullName        VARCHAR2(100) NOT NULL,
    Specialization  VARCHAR2(100) NOT NULL,
    Qualifications  VARCHAR2(500),
    ProfileDetails  CLOB,
    Email           VARCHAR2(100) NOT NULL,
    PhoneNumber     VARCHAR2(20),
    CreatedAt       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UpdatedAt       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

COMMENT ON TABLE TRAINERS IS 'Instructor master repository with credentials, bios, and contacts';
COMMENT ON COLUMN TRAINERS.TrainerID IS 'Surrogate primary key for trainer';
COMMENT ON COLUMN TRAINERS.ProfileDetails IS 'SecureFile CLOB storing extensive biography and publications';

-- ----------------------------------------------------------------------------
-- 4. Table: COURSES
-- Purpose: Master catalog of courses with objectives, prerequisites, and pricing
-- ----------------------------------------------------------------------------
CREATE TABLE COURSES (
    CourseID            NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,
    CategoryID          NUMBER NOT NULL,
    CourseName          VARCHAR2(150) NOT NULL,
    Description         CLOB,
    LearningObjectives  CLOB,
    Prerequisites       VARCHAR2(500),
    Price               NUMBER(10,2) NOT NULL,
    Duration            NUMBER(5,0) NOT NULL,
    DeliveryMode        VARCHAR2(50) NOT NULL,
    IsFeatured          NUMBER(1,0) DEFAULT 0 NOT NULL,
    CreatedAt           TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UpdatedAt           TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

COMMENT ON TABLE COURSES IS 'Educational course offerings master definitions';
COMMENT ON COLUMN COURSES.CourseID IS 'Surrogate primary key for course';
COMMENT ON COLUMN COURSES.CategoryID IS 'Foreign key referencing CATEGORIES(CategoryID)';
COMMENT ON COLUMN COURSES.Price IS 'Standard registration tuition fee (non-negative)';
COMMENT ON COLUMN COURSES.Duration IS 'Course duration in instructional hours';
COMMENT ON COLUMN COURSES.DeliveryMode IS 'Delivery channel: In-Person, Online, Hybrid, Classroom';
COMMENT ON COLUMN COURSES.IsFeatured IS 'Boolean flag (1=Featured on Home Page, 0=Standard)';

-- ----------------------------------------------------------------------------
-- 5. Table: COURSEOFFERINGS
-- Purpose: Specific scheduled class runs with assigned trainer and capacity
-- ----------------------------------------------------------------------------
CREATE TABLE COURSEOFFERINGS (
    OfferingID          NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,
    CourseID            NUMBER NOT NULL,
    TrainerID           NUMBER NOT NULL,
    StartDate           DATE NOT NULL,
    EndDate             DATE NOT NULL,
    ScheduleDetails     VARCHAR2(255) NOT NULL,
    MaxCapacity         NUMBER NOT NULL,
    AvailableSeats      NUMBER NOT NULL,
    CreatedAt           TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UpdatedAt           TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

COMMENT ON TABLE COURSEOFFERINGS IS 'Scheduled training class instances with seat inventory';
COMMENT ON COLUMN COURSEOFFERINGS.OfferingID IS 'Surrogate primary key for course offering';
COMMENT ON COLUMN COURSEOFFERINGS.MaxCapacity IS 'Maximum enrollment ceiling for this offering (>0)';
COMMENT ON COLUMN COURSEOFFERINGS.AvailableSeats IS 'Real-time remaining seat inventory (0 to MaxCapacity)';

-- ----------------------------------------------------------------------------
-- 6. Table: TRAINEES
-- Purpose: Student and attendee records
-- ----------------------------------------------------------------------------
CREATE TABLE TRAINEES (
    TraineeID               NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,
    FullName                VARCHAR2(100) NOT NULL,
    Email                   VARCHAR2(100) NOT NULL,
    PhoneNumber             VARCHAR2(20) NOT NULL,
    EducationalBackground   VARCHAR2(255) NOT NULL,
    CreatedAt               TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UpdatedAt               TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

COMMENT ON TABLE TRAINEES IS 'Registered students and training course participants';
COMMENT ON COLUMN TRAINEES.TraineeID IS 'Surrogate primary key for trainee';
COMMENT ON COLUMN TRAINEES.Email IS 'Unique trainee email used for registration and identification';

-- ----------------------------------------------------------------------------
-- 7. Table: REGISTRATIONS
-- Purpose: Enrollment records linking trainees to scheduled course offerings
-- ----------------------------------------------------------------------------
CREATE TABLE REGISTRATIONS (
    RegistrationID      NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,
    TraineeID           NUMBER NOT NULL,
    OfferingID          NUMBER NOT NULL,
    RegistrationDate    DATE DEFAULT SYSDATE NOT NULL,
    Status              VARCHAR2(30) DEFAULT 'Pending' NOT NULL,
    CancellationReason  VARCHAR2(255),
    CancellationDate    TIMESTAMP,
    CreatedAt           TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UpdatedAt           TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

COMMENT ON TABLE REGISTRATIONS IS 'Course enrollment transactions and attendance statuses';
COMMENT ON COLUMN REGISTRATIONS.RegistrationID IS 'Surrogate primary key for registration';
COMMENT ON COLUMN REGISTRATIONS.Status IS 'Enrollment state: Pending, Confirmed, Cancelled';
